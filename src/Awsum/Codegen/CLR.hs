-- | CLR textual CIL assembler for Awsum 'Core'.
--
-- Produces a human-readable ilasm-like text representation of the
-- CIL bytecode that 'Awsum.Codegen.CLR.Assemble' generates as binary.
-- Used for @awsum asm -t clr@ output and snapshot tests.
module Awsum.Codegen.CLR (codegenCLR) where

import Awsum.Core
import Data.Char qualified as Char
import Data.Map.Strict qualified as Map
import Data.Set qualified as Set
import Data.Text qualified as T
import Relude

-- ════════════════════════════════════════════════════════════════════════════
-- Public API
-- ════════════════════════════════════════════════════════════════════════════

-- | Produce a textual CIL assembly from a Core program.
codegenCLR :: CoreProgram -> Text
codegenCLR (CoreProgram decls) =
  let valNames = Set.fromList [n | CValDef n _ <- decls]
      funNames = Set.fromList [n | CFunDef n _ _ <- decls]
      arities = Map.fromList [(n, length as) | CFunDef n as _ <- decls]
      ctx = Ctx {cValDefs = valNames, cFunDefs = funNames, cArities = arities}
   in T.intercalate "\n"
        $ filter
          (not . T.null)
          [ assemblyHeader,
            "",
            classOpen,
            "",
            initMethod,
            "",
            concatMethod,
            "",
            printMethod,
            "",
            T.intercalate "\n\n" (map (emitDecl ctx) decls),
            "",
            mainMethod,
            "",
            classClose,
            ""
          ]

-- ════════════════════════════════════════════════════════════════════════════
-- Context
-- ════════════════════════════════════════════════════════════════════════════

data Ctx = Ctx
  { cValDefs :: Set Text,
    cFunDefs :: Set Text,
    cArities :: Map Text Int
  }

-- ════════════════════════════════════════════════════════════════════════════
-- Fixed sections
-- ════════════════════════════════════════════════════════════════════════════

assemblyHeader :: Text
assemblyHeader =
  unlines
    [ "// Awsum CLR codegen — ilasm-like syntax, not compatible with ilasm.",
      "// This is a textual representation of the bytecode generated by assembleCLR.",
      ".assembly extern System.Runtime {}",
      ".assembly extern System.Console {}",
      ".assembly AwsumMain {}",
      ".module AwsumMain.dll"
    ]

classOpen :: Text
classOpen = ".class public auto ansi AwsumMain extends [System.Runtime]System.Object\n{"

classClose :: Text
classClose = "}"

initMethod :: Text
initMethod =
  unlines
    [ "  .method public hidebysig specialname rtspecialname instance void .ctor() cil managed",
      "  {",
      "    ldarg.0",
      "    call instance void [System.Runtime]System.Object::.ctor()",
      "    ret",
      "  }"
    ]

concatMethod :: Text
concatMethod =
  unlines
    [ "  .method public hidebysig static object __concat(object, object) cil managed",
      "  {",
      "    ldarg.0",
      "    ldarg.1",
      "    call string [System.Runtime]System.String::Concat(object, object)",
      "    ret",
      "  }"
    ]

printMethod :: Text
printMethod =
  unlines
    [ "  .method public hidebysig static object __print(object) cil managed",
      "  {",
      "    ldarg.0",
      "    call void [System.Console]System.Console::Write(object)",
      "    ldnull",
      "    ret",
      "  }"
    ]

mainMethod :: Text
mainMethod =
  unlines
    [ "  .method public hidebysig static void Main(string[]) cil managed",
      "  {",
      "    .entrypoint",
      "    ldarg.0",
      "    ldlen",
      "    conv.i4",
      "    ldc.i4.1",
      "    bge.s has_arg",
      "    ldstr \"\"",
      "    br.s call_main",
      "  has_arg:",
      "    ldarg.0",
      "    ldc.i4.0",
      "    ldelem.ref",
      "  call_main:",
      "    call object AwsumMain::" <> mangle "main" <> "(object)",
      "    pop",
      "    ret",
      "  }"
    ]

-- ════════════════════════════════════════════════════════════════════════════
-- User declarations
-- ════════════════════════════════════════════════════════════════════════════

emitDecl :: Ctx -> CDecl -> Text
emitDecl ctx = \case
  CFunDef nm args body ->
    let paramCtx = Map.fromList (zip args [0 ..])
        desc = objMethodDesc (length args)
        bodyText = emitExprText ctx paramCtx body
     in unlines
          [ "  .method public hidebysig static object " <> mangle nm <> desc <> " cil managed",
            "  {",
            bodyText,
            "    ret",
            "  }"
          ]
  CValDef nm rhs ->
    let bodyText = emitExprText ctx Map.empty rhs
     in unlines
          [ "  .method public hidebysig static object " <> mangle nm <> "() cil managed",
            "  {",
            bodyText,
            "    ret",
            "  }"
          ]

-- ════════════════════════════════════════════════════════════════════════════
-- Expression emission (text)
-- ════════════════════════════════════════════════════════════════════════════

emitExprText :: Ctx -> Map Text Int -> CExpr -> Text
emitExprText ctx paramMap = \case
  CString s ->
    "    ldstr " <> show s
  CVar n
    | Just slot <- Map.lookup n paramMap ->
        "    ldarg" <> ldargSuffix slot
    | n `Set.member` ctx.cValDefs ->
        "    call object AwsumMain::" <> mangle n <> "()"
    | n `Set.member` ctx.cFunDefs ->
        let arity = fromMaybe 0 (Map.lookup n ctx.cArities)
         in "    ldftn object AwsumMain::"
              <> mangle n
              <> objMethodDesc arity
              <> "\n"
              <> "    newobj instance void class [System.Runtime]System.Func`"
              <> show (arity + 1)
              <> "<"
              <> T.intercalate ", " (replicate (arity + 1) "object")
              <> ">::.ctor(object, native int)"
    | otherwise ->
        "    ldnull"
  CPrim _ ->
    "    ldnull"
  CCall f xs ->
    case f of
      CPrim PrimConcat
        | [a, b] <- xs ->
            T.intercalate
              "\n"
              [ emitExprText ctx paramMap a,
                emitExprText ctx paramMap b,
                "    call object AwsumMain::__concat(object, object)"
              ]
      CPrim PrimPrint
        | [x] <- xs ->
            T.intercalate
              "\n"
              [ emitExprText ctx paramMap x,
                "    call object AwsumMain::__print(object)"
              ]
      CVar n
        | n `Set.member` ctx.cFunDefs ->
            let argTexts = map (emitExprText ctx paramMap) xs
                desc = objMethodDesc (length xs)
             in T.intercalate "\n"
                  $ argTexts
                  <> ["    call object AwsumMain::" <> mangle n <> desc]
      _ ->
        let fText = emitExprText ctx paramMap f
            argTexts = map (emitExprText ctx paramMap) xs
            arity = length xs
            funcType =
              "class [System.Runtime]System.Func`"
                <> show (arity + 1)
                <> "<"
                <> T.intercalate ", " (replicate (arity + 1) "object")
                <> ">"
            invokeDesc = "(" <> T.intercalate ", " (replicate arity "object") <> ")"
         in T.intercalate "\n"
              $ [fText, "    castclass " <> funcType]
              <> argTexts
              <> ["    callvirt instance object " <> funcType <> "::Invoke" <> invokeDesc]

-- ════════════════════════════════════════════════════════════════════════════
-- Helpers
-- ════════════════════════════════════════════════════════════════════════════

mangle :: Text -> Text
mangle t =
  let ok c = Char.isAlphaNum c || c == '_' || c == '\''
      body = T.map (\c -> if ok c then c else '_') t
   in "v_" <> body

objMethodDesc :: Int -> Text
objMethodDesc n =
  "(" <> T.intercalate ", " (replicate n "object") <> ")"

ldargSuffix :: Int -> Text
ldargSuffix n
  | n <= 3 = "." <> show n
  | otherwise = " " <> show n
