      "    ldarg.1",
      "    unbox.any [System.Runtime]System.Int32",
      "    stloc.1",
      "    ldloc.0",
      "    ldloc.1",
      "    add",
      "    stloc.2",
      "    ldloc.0",
      "    ldloc.2",
      "    xor",
      "    ldloc.1",
      "    ldloc.2",
      "    xor",
      "    and",
      "    ldc.i4.0",
      "    blt.s IL_addi32_over",
      "    ldc.i4.2",
      "    newarr [System.Runtime]System.Object",
      "    dup",
