-- | CLR textual CIL assembler for Awsum 'Core'.
--
-- Produces a human-readable ilasm-like text representation of the
-- CIL bytecode that 'Awsum.Codegen.CLR.Assemble' generates as binary.
-- Used for @awsum asm -t clr@ output and snapshot tests.
module Awsum.Codegen.CLR (codegenCLR) where

import Awsum.Codegen.CLR.Assemble (CilModule (..), cilModule)
import Awsum.Codegen.CLR.Instr (renderCilMethod)
import Awsum.Core
import Data.Text qualified as T
import Relude

-- ════════════════════════════════════════════════════════════════════════════
-- Public API
-- ════════════════════════════════════════════════════════════════════════════

-- | Produce a textual CIL assembly from a Core program. This and the byte
--   assembler both render from one 'cilModule' value, so the @.il@ text is a
--   faithful view of the shipped @.dll@.
codegenCLR :: PreludeTags -> CoreProgram -> Text
codegenCLR ptags prog = renderCilModule (cilModule ptags prog)

-- | Render a 'CilModule' to ilasm-like text: fixed framing (assembly header,
--   class open, @.ctor@) followed by the gated methods, then the class close.
--   Helpers and entry are single-spaced; user declarations are double-spaced
--   (each 'renderCilMethod' already ends in a newline).
renderCilModule :: CilModule -> Text
renderCilModule m =
  T.intercalate "\n"
    $ filter (not . T.null)
    $ [assemblyHeader, "", classOpen, "", initMethod]
    <> concatMap (\meth -> ["", renderCilMethod meth]) (clmHelpers m)
    <> ["", T.intercalate "\n\n" (map renderCilMethod (clmUserDefs m))]
    <> concatMap (\meth -> ["", renderCilMethod meth]) (clmEntry m)
    <> ["", classClose, ""]

-- ════════════════════════════════════════════════════════════════════════════
-- Fixed framing
-- ════════════════════════════════════════════════════════════════════════════

assemblyHeader :: Text
assemblyHeader =
  unlines
    [ "// Awsum CLR codegen — ilasm-like syntax, not compatible with ilasm.",
      "// This is a textual representation of the bytecode generated by assembleCLR.",
      ".assembly extern System.Runtime {}",
      ".assembly extern System.Console {}",
      ".assembly AwsumMain {}",
      ".module AwsumMain.dll"
    ]

classOpen :: Text
classOpen = ".class public auto ansi AwsumMain extends [System.Runtime]System.Object\n{"

classClose :: Text
classClose = "}"

initMethod :: Text
initMethod =
  unlines
    [ "  .method private hidebysig specialname rtspecialname instance void .ctor() cil managed",
      "  {",
      "    ldarg.0",
      "    call instance void [System.Runtime]System.Object::.ctor()",
      "    ret",
      "  }"
    ]
