-- | @__inc_ref@: bump the refcount of a heap cell. Reads the @flag@ word at
--   @p - 12@; a @0@ flag marks a data-section literal (no refcount), so the
--   helper returns early. Otherwise it increments the refcount word at @p - 8@
--   in place. Void result. Local 0 is the param @p@; local 1 is @flag@.
incRefSpec :: WasmFunc
incRefSpec =
  WasmFunc
    { wfName = "__inc_ref",
      wfParams = [I32],
      wfResults = [],
      wfLocals = [I32],
      wfBody =
        [ -- flag = load (p - 12)
          LocalGet 0,
          I32Const 12,
          I32Sub,
          I32Load (MemArg 2 0),
          LocalSet 1,
          -- if flag == 0: return (literal, no refcount)
          LocalGet 1,
          I32Eqz,
          If BtVoid,
          Return,
          End,
          -- store (p - 8) := load (p - 8) + 1
          LocalGet 0,
          I32Const 8,
          I32Sub,
          LocalGet 0,
          I32Const 8,
          I32Sub,
          I32Load (MemArg 2 0),
          I32Const 1,
          I32Add,
          I32Store (MemArg 2 0)
        ]
    }

