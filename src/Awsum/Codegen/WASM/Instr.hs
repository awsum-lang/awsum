-- | A WASM value type (the subset Awsum's codegen uses — all values are @i32@
--   pointers; @i64@ appears only inside a few arithmetic helpers).
data ValType = I32 | I64
  deriving stock (Eq, Show)

-- | A structured-control block's result type. WASM blocks/loops/ifs either
--   produce nothing (@BtVoid@ = 0x40) or a single @i32@ / @i64@.
data BlockType = BtVoid | BtI32 | BtI64
  deriving stock (Eq, Show)

-- | A memory access immediate: alignment (as the binary log2 exponent — 2 means
--   4-byte natural alignment for @i32@) and a byte offset. Awsum's accesses are
--   always naturally aligned, so the text omits @align@ and only prints a
--   non-zero @offset@.
data MemArg = MemArg
  { maAlign :: Int,
    maOffset :: Int
  }
  deriving stock (Eq, Show)

-- | One abstract WASM instruction. Operands are symbolic where the two
--   projections would otherwise diverge: a call carries the callee's /name/, not
--   its function index.
data WasmInstr
  = I32Const Int
  | -- | @call@ a sibling function by name; the assembler resolves it to a
    --   function index through the shared name→index map, and the text renders
    --   the same numeric index.
    Call Text
  | -- | @call@ a function by its already-resolved numeric index. User-code
    --   emission works from @ecFuncIdx@ (indices, not names), so it uses this
    --   directly; encodes and renders exactly like 'Call' after name lookup.
    CallIdx Int
  | -- | @call_indirect (type N)@ through table 0 — the post-@LowerClosures@
    --   @$applyN@ dispatch for residual higher-order calls. Carries the type
    --   index; the table index is always @0@.
    CallIndirect Int
  | LocalGet Int
  | LocalSet Int
  | LocalTee Int
  | -- | Module globals, addressed by numeric index (globals live in their own
    --   index space, not the function space, so they stay numeric rather than
    --   symbolic). Awsum uses four: @0@ heap bump pointer, @1@ free-worklist
    --   buffer, @2@ free-worklist top, @3@ free-worklist capacity.
    GlobalGet Int
  | GlobalSet Int
  | I32Load MemArg
  | I32Store MemArg
  | -- | Single-byte memory access (unsigned-extended load / truncating store);
    --   used by @__memcpy@. Natural alignment is @0@ (@MemArg 0 _@).
    I32Load8U MemArg
  | I32Store8 MemArg
  | -- | Structured control. @Block@/@Loop@/@If@ open a nesting level closed by a
    --   matching 'End'; 'Br'/'BrIf' jump out by relative depth (0 = innermost
    --   enclosing block). 'If' consumes the top-of-stack i32 condition; 'Else'
    --   splits its arms. The 'BlockType' is the value left on the stack
    --   (@BtVoid@ for none — the common case for these control wrappers).
    Block BlockType
  | Loop BlockType
  | If BlockType
  | Else
  | End
  | Br Int
  | BrIf Int
  | -- | Early return from the enclosing function.
    Return
  | -- | Trap. @__alloc_shaped@ reaches it only if @memory.grow@ fails (OOM).
    Unreachable
  | -- | Discard the top-of-stack value. @__print@ drops the @fd_write@ result.
    Drop
  | I32Add
  | I32Sub
  | I32Mul
  | -- | Unsigned division / remainder — the @show@ helpers extract decimal
    --   digits with @i32.div_u@ / @i32.rem_u@ by 10.
    I32DivU
  | I32RemU
  | I32And
  | I32Xor
  | I32Shl
  | I32Eqz
  | I32Eq
  | I32Ne
  | I32LtS
  | I32LtU
  | I32GeS
  | I32GeU
  | I32GtU
  | I32LeU
  | -- | Count trailing / leading zero bits — @__free@ derives a size-class bin
    --   index from a power-of-two rounded size with @i32.ctz@; @__alloc_shaped@
    --   rounds a request up to the next power-of-two bin with @i32.clz@.
    I32Ctz
  | I32Clz
  | -- | 64-bit arithmetic + i32↔i64 conversions. The overflow-checking integer
    --   helpers (@__addInt32@, @__mulInt32@, …) widen both operands to @i64@,
    --   do the op without loss, then range-check before truncating back: e.g.
    --   @i64.extend_i32_s@ the inputs, @i64.mul@, compare against the i32 bounds
    --   as @i64@ constants, and @i32.wrap_i64@ the result on the in-range arm.
    I64Const Int
  | I64Add
  | I64Sub
  | I64Mul
  | I64Shl
  | I64LtS
  | I64GtS
  | I64GtU
  | I32WrapI64
  | I64ExtendI32S
  | I64ExtendI32U
  | -- | Linear-memory size / grow, in 64 KiB pages. Both carry the single
    --   memory index @0@ as an implicit immediate (emitted as a @0x00@ byte).
    --   @__alloc_shaped@ uses them to extend the heap when a bin is empty.
    MemorySize
  | MemoryGrow
  deriving stock (Eq, Show)

-- | A function: name (a readable @$label@ in the WAT header — it never reaches
--   the code-section bytes), parameter and result types, the extra locals
--   (beyond the params), and the linear body. Both projections share these, so
--   the WAT @(func …)@ header and the binary type/locals declarations cannot
--   disagree.
data WasmFunc = WasmFunc
  { wfName :: Text,
    wfParams :: [ValType],
    wfResults :: [ValType],
    wfLocals :: [ValType],
    wfBody :: [WasmInstr]
  }
  deriving stock (Eq, Show)

renderValType :: ValType -> Text
renderValType I32 = "i32"
renderValType I64 = "i64"

-- | Plain (unfolded) WAT text for a function: a @(func $name (param …)(result …)
--   (local …) <body>)@ with the body as a flat instruction listing — one per
--   line, references numeric. Mirrors the byte projection 1:1.
renderWat :: Map Text Word32 -> WasmFunc -> Text
renderWat idxMap f =
  T.intercalate "\n" (header : locals <> body) <> ")"
  where
    header =
      "  (func $"
        <> wfName f
        <> grp "param" (wfParams f)
        <> grp "result" (wfResults f)
    grp _ [] = ""
    grp kw vts = " (" <> kw <> " " <> unwords (map renderValType vts) <> ")"
    locals = ["    (local " <> renderValType vt <> ")" | vt <- wfLocals f]
    body = map (("    " <>) . renderInstr idxMap) (wfBody f)

renderInstr :: Map Text Word32 -> WasmInstr -> Text
renderInstr idxMap = \case
  I32Const n -> "i32.const " <> show n
  Call name -> "call " <> show (lookupIdx name)
  CallIdx idx -> "call " <> show idx
  CallIndirect ty -> "call_indirect (type " <> show ty <> ")"
  LocalGet n -> "local.get " <> show n
  LocalSet n -> "local.set " <> show n
  LocalTee n -> "local.tee " <> show n
  GlobalGet n -> "global.get " <> show n
  GlobalSet n -> "global.set " <> show n
  I32Load m -> "i32.load" <> memArgSuffix m
  I32Store m -> "i32.store" <> memArgSuffix m
  I32Load8U m -> "i32.load8_u" <> memArgSuffix m
  I32Store8 m -> "i32.store8" <> memArgSuffix m
  Block bt -> "block" <> blockTypeSuffix bt
  Loop bt -> "loop" <> blockTypeSuffix bt
  If bt -> "if" <> blockTypeSuffix bt
  Else -> "else"
  End -> "end"
  Br n -> "br " <> show n
  BrIf n -> "br_if " <> show n
  Return -> "return"
  Unreachable -> "unreachable"
  Drop -> "drop"
  I32Add -> "i32.add"
  I32Sub -> "i32.sub"
  I32Mul -> "i32.mul"
  I32DivU -> "i32.div_u"
  I32RemU -> "i32.rem_u"
  I32And -> "i32.and"
  I32Xor -> "i32.xor"
  I32Shl -> "i32.shl"
  I32Eqz -> "i32.eqz"
  I32Eq -> "i32.eq"
  I32Ne -> "i32.ne"
  I32LtS -> "i32.lt_s"
  I32LtU -> "i32.lt_u"
  I32GeS -> "i32.ge_s"
  I32GeU -> "i32.ge_u"
  I32GtU -> "i32.gt_u"
  I32LeU -> "i32.le_u"
  I32Ctz -> "i32.ctz"
  I32Clz -> "i32.clz"
  I64Const n -> "i64.const " <> show n
  I64Add -> "i64.add"
  I64Sub -> "i64.sub"
  I64Mul -> "i64.mul"
  I64Shl -> "i64.shl"
  I64LtS -> "i64.lt_s"
  I64GtS -> "i64.gt_s"
  I64GtU -> "i64.gt_u"
  I32WrapI64 -> "i32.wrap_i64"
  I64ExtendI32S -> "i64.extend_i32_s"
  I64ExtendI32U -> "i64.extend_i32_u"
  MemorySize -> "memory.size"
  MemoryGrow -> "memory.grow"
  where
    lookupIdx name = fromMaybe (error ("WASM.Instr: no index for " <> name)) (Map.lookup name idxMap)

-- | A memory access prints only its non-default operands: natural alignment and
--   a zero offset are the assumed defaults, matching the bytes (a @0@ offset is
--   still encoded, but the text omits it for legibility).
memArgSuffix :: MemArg -> Text
memArgSuffix (MemArg _ o) = if o /= 0 then " offset=" <> show o else ""

-- | A structured block's result annotation, plain-WAT form. @BtVoid@ prints
--   nothing (the byte is @0x40@); a value type prints @(result …)@.
blockTypeSuffix :: BlockType -> Text
blockTypeSuffix = \case
  BtVoid -> ""
  BtI32 -> " (result i32)"
  BtI64 -> " (result i64)"

