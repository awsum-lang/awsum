-- | FNV-1a 32-bit row tags for the prelude's @OverflowError@ / @UnderflowError@
--   labels, the @CRow@ box tag of the @Left@ the overflow-checking arithmetic
--   helpers build. Computed via 'rowTag' (= @Awsum.HM.canonicalLabel@) so they
--   stay in lockstep with the user-side @CRowCase@ comparison without magic
--   numbers. Program-independent, so the spec computes them rather than taking
--   them as parameters. Stored as 'Int' here; 'asmInstr' truncates to the same
--   @Int32@ bit pattern the binary's @encodeSLEB128@ sees, and the value printed
--   by 'renderWat' matches the text codegen's @show (rowTag …)@.
overflowRowTag :: Int
overflowRowTag = fromIntegral (rowTag (TyCon noSpan "OverflowError"))

underflowRowTag :: Int
underflowRowTag = fromIntegral (rowTag (TyCon noSpan "UnderflowError"))

