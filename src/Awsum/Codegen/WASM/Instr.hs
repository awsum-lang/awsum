-- | Unified WASM instruction IR — the single source of truth behind both WASM
--   projections. One 'WasmFunc' value — a flat list of 'WasmInstr' with
--   operands carried *symbolically* (function refs by name, never an index) —
--   feeds two total, decision-free projections, so they cannot diverge on
--   "which function" a call denotes:
--
--     * 'renderWat' here, which prints the WAT text.
--     * 'Awsum.Codegen.WASM.Assemble.assembleFunc', which resolves the symbolic
--       call targets to function indices and emits the code-section bytes.
--
--   The IR is /linear/ and /numeric/ — it matches WASM's true (post-folding)
--   structure: explicit @block@/@loop@/@if@/@end@, @br@ by numeric depth,
--   @local.get N@ / @call N@ by index. The rendered @.wat@ is therefore the
--   plain (unfolded) text form, which honestly shows what the @.wasm@ bytes run,
--   rather than the folded s-expression sugar.
