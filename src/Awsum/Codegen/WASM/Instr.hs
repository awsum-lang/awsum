--   to mirror the source; 'asmInstr' truncates to the matching @Int32@ pattern.
stringTooLongTagWord :: Word32
stringTooLongTagWord = rowTag (TyCon noSpan "StringTooLong")

unpairedSurrogateTagWord :: Word32
