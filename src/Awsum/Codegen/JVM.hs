-- | JVM textual bytecode assembler for Awsum 'Core'.
--
-- Produces a human-readable Jasmin-like text representation of the
-- JVM bytecode that 'Awsum.Codegen.JVM.Assemble' generates as binary.
-- Used for @awsum build -t jvm@ output and snapshot tests.
module Awsum.Codegen.JVM (codegenJVM) where

import Awsum.Codegen.JVM.Assemble (JvmModule (..), jvmModule)
import Awsum.Codegen.JVM.Instr (renderMethod)
import Awsum.Core
import Data.Text qualified as T
import Relude

-- ════════════════════════════════════════════════════════════════════════════
-- Public API
-- ════════════════════════════════════════════════════════════════════════════

-- | Produce a textual JVM bytecode assembly from a Core program. This and the
--   byte assembler both render from one 'jvmModule' value, so the @.j@ text is
--   a faithful view of the shipped @.class@.
codegenJVM :: PreludeTags -> CoreProgram -> Text
codegenJVM ptags prog = renderJvmModule (jvmModule ptags prog)

-- | Render a 'JvmModule' to Jasmin-like text: fixed framing (class header,
--   @<init>@) followed by the gated methods. Helpers and entry are
--   single-spaced; user declarations are double-spaced. Each 'renderMethod'
--   already ends in a newline, so a "" between methods yields one blank line
--   and the "\n\n" within the user block yields two.
renderJvmModule :: JvmModule -> Text
renderJvmModule m =
  T.intercalate "\n"
    $ filter (not . T.null)
    $ [classHeader, "", initMethod]
    <> concatMap (\meth -> ["", renderMethod meth]) (jmHelpers m)
    <> ["", T.intercalate "\n\n" (map renderMethod (jmUserDefs m))]
    <> concatMap (\meth -> ["", renderMethod meth]) (jmEntry m)
    <> [""]

-- ════════════════════════════════════════════════════════════════════════════
-- Fixed framing
-- ════════════════════════════════════════════════════════════════════════════

classHeader :: Text
classHeader =
  unlines
    [ "; Awsum JVM codegen — Jasmin-like syntax, not compatible with Jasmin.",
      "; This is a textual representation of the bytecode generated by assembleJVM.",
      ".bytecode 55.0",
      ".class public AwsumMain",
      ".super java/lang/Object",
      -- Stashed reference to the 'args' array passed to 'public static
      -- main(String[])'. Read by '__getArgs' to walk every argv element
      -- and build a prelude 'List String' on demand. Always emitted (the
      -- store in 'mainSpec' is unconditional) so the snapshot stays
      -- stable regardless of which built-ins the user program touches.
      ".field private static __argv [Ljava/lang/String;"
    ]

initMethod :: Text
initMethod =
  unlines
    [ ".method <init>()V",
      "  aload_0",
      "  invokespecial java/lang/Object/<init>()V",
      "  return",
      ".end method"
    ]
