mangle :: Text -> Text
mangle t =
  let ok c = Char.isAlphaNum c || c == '_' || c == '\''
      body = T.map (\c -> if ok c then c else '_') t
   in "v_" <> body

objDesc :: Text
objDesc = "Ljava/lang/Object;"

objMethodDescText :: Int -> Text
objMethodDescText n =
  "(" <> T.replicate n objDesc <> ")" <> objDesc

aloadSuffix :: Int -> Text
aloadSuffix n
  | n <= 3 = "_" <> show n
  | otherwise = " " <> show n

astoreSuffix :: Int -> Text
astoreSuffix n
  | n <= 3 = "_" <> show n
  | otherwise = " " <> show n
